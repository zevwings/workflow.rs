//! 基础设施服务层模块
//!
//! 本模块提供基础设施服务层的功能，包括：
//! - 接口定义（traits）：定义抽象接口，实现依赖倒置
//! - 适配器实现（adapters）：将不同实现适配为统一接口
//! - 服务聚合（services）：聚合多个服务，提供统一访问
//! - 管理器（managers）：管理服务生命周期和配置
//!
//! ## 架构层次
//!
//! ```text
//! util/http/logger/settings → 底层工具和组件
//! infra/                    → 基础设施服务层（接口、适配器、服务聚合）
//! pr/jira/                  → 业务逻辑层
//! ```
//!
//! ## 设计原则
//!
//! 1. **依赖倒置**：通过 trait 定义接口，业务模块依赖抽象而非具体实现
//! 2. **适配器模式**：将不同实现适配为统一接口
//! 3. **服务聚合**：统一管理多个服务，提供便捷访问
//! 4. **解耦**：通过抽象层实现模块间的解耦

